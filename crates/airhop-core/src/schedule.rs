/// Inclusive local-date range requested from the materializer.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ScheduleRange {
    /// First effective date, inclusive.
    pub starts_on: NaiveDate,
    /// Last effective date, inclusive.
    pub ends_on: NaiveDate,
}

/// Options controlling schedule materialization.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct MaterializeScheduleOptions {
    /// Include archived groups and recurrence rules for historical reads.
    pub include_archived: bool,
}

/// A deterministic schedule materialization failure.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum ScheduleError {
    /// The requested effective-date range is reversed.
    #[error("schedule range is reversed")]
    ReversedRange,
    /// A recurrence rule has a reversed date range.
    #[error("recurrence rule {rule_id} has a reversed date range")]
    ReversedRuleRange {
        /// Invalid rule.
        rule_id: Uuid,
    },
    /// A recurrence rule ends at or before it starts.
    #[error("recurrence rule {rule_id} has an invalid time range")]
    InvalidRuleTime {
        /// Invalid rule.
        rule_id: Uuid,
    },
    /// A recurrence rule has no weekdays.
    #[error("recurrence rule {rule_id} has no weekdays")]
    EmptyRuleWeekdays {
        /// Invalid rule.
        rule_id: Uuid,
    },
    /// A recurrence rule repeats a teacher.
    #[error("recurrence rule {rule_id} contains duplicate teachers")]
    DuplicateTeachers {
        /// Invalid rule.
        rule_id: Uuid,
    },
    /// A rule refers to a missing group.
    #[error("recurrence rule {rule_id} refers to missing group {group_id}")]
    MissingGroup {
        /// Rule with the broken reference.
        rule_id: Uuid,
        /// Missing group.
        group_id: Uuid,
    },
    /// More than one exception targets the same stable occurrence.
    #[error("multiple exceptions target recurrence rule {rule_id} on {original_date}")]
    DuplicateException {
        /// Target rule.
        rule_id: Uuid,
        /// Target original date.
        original_date: NaiveDate,
    },
    /// An exception does not address a date generated by its rule.
    #[error("exception {exception_id} targets a non-occurrence date")]
    InvalidExceptionReference {
        /// Invalid exception.
        exception_id: Uuid,
    },
    /// Final effective start/end values are invalid.
    #[error("occurrence for rule {rule_id} on {original_date} has an invalid time range")]
    InvalidEffectiveTime {
        /// Target rule.
        rule_id: Uuid,
        /// Stable original date.
        original_date: NaiveDate,
    },
    /// Iterating a date range overflowed the supported calendar.
    #[error("schedule date range overflow")]
    DateOverflow,
}

/// Materializes all occurrences whose effective date falls in `range`.
///
/// Moved exceptions are included when their original date is outside the
/// requested range but their effective date falls inside it.
pub fn materialize_schedule(
    policy: &SchedulePolicy,
    groups: &[GroupSchedulePolicy],
    rules: &[RecurrenceRule],
    exceptions: &[LessonException],
    range: ScheduleRange,
    options: MaterializeScheduleOptions,
) -> Result<Vec<ScheduleOccurrence>, ScheduleError> {
    if range.starts_on > range.ends_on {
        return Err(ScheduleError::ReversedRange);
    }

    let group_by_id: BTreeMap<Uuid, &GroupSchedulePolicy> =
        groups.iter().map(|group| (group.id, group)).collect();
    let mut exception_by_ref = BTreeMap::new();
    for exception in exceptions {
        let reference = StableLessonReference {
            recurrence_rule_id: exception.recurrence_rule_id,
            original_date: exception.original_date,
        };
        if exception_by_ref.insert(reference, exception).is_some() {
            return Err(ScheduleError::DuplicateException {
                rule_id: reference.recurrence_rule_id,
                original_date: reference.original_date,
            });
        }
    }

    let mut occurrences = BTreeMap::new();
    for rule in rules {
        rule.validate()?;
        let group =
            group_by_id
                .get(&rule.group_id)
                .copied()
                .ok_or(ScheduleError::MissingGroup {
                    rule_id: rule.id,
                    group_id: rule.group_id,
                })?;
        if !options.include_archived && (!group.active || !rule.active) {
            continue;
        }

        let first_date = rule.starts_on.max(range.starts_on);
        let last_date = rule.ends_on.min(range.ends_on);
        if first_date <= last_date {
            let mut date = first_date;
            loop {
                if rule.occurs_on(date) {
                    let reference = StableLessonReference {
                        recurrence_rule_id: rule.id,
                        original_date: date,
                    };
                    let occurrence = materialize_occurrence(
                        policy,
                        group,
                        rule,
                        date,
                        exception_by_ref.get(&reference).copied(),
                    )?;
                    occurrences.insert(reference, occurrence);
                }
                if date == last_date {
                    break;
                }
                date = date.succ_opt().ok_or(ScheduleError::DateOverflow)?;
            }
        }

        for exception in exceptions
            .iter()
            .filter(|exception| exception.recurrence_rule_id == rule.id)
        {
            if !rule.occurs_on(exception.original_date) {
                return Err(ScheduleError::InvalidExceptionReference {
                    exception_id: exception.id,
                });
            }
            if exception.original_date >= first_date && exception.original_date <= last_date {
                continue;
            }
            let Some(target_date) = exception_target_date(exception) else {
                continue;
            };
            if target_date < range.starts_on || target_date > range.ends_on {
                continue;
            }
            let reference = StableLessonReference {
                recurrence_rule_id: rule.id,
                original_date: exception.original_date,
            };
            let occurrence = materialize_occurrence(
                policy,
                group,
                rule,
                exception.original_date,
                Some(exception),
            )?;
            occurrences.insert(reference, occurrence);
        }
    }

    let mut result: Vec<_> = occurrences
        .into_values()
        .filter(|occurrence| occurrence.date >= range.starts_on && occurrence.date <= range.ends_on)
        .collect();
    result.sort_by_key(|occurrence| {
        (
            occurrence.date,
            occurrence.start_time,
            occurrence.lesson_ref,
        )
    });
    Ok(result)
}

/// Materializes one stable occurrence, or returns `None` when the rule does not own it.
pub fn materialize_schedule_occurrence(
    policy: &SchedulePolicy,
    group: &GroupSchedulePolicy,
    rule: &RecurrenceRule,
    exception: Option<&LessonException>,
    original_date: NaiveDate,
) -> Result<Option<ScheduleOccurrence>, ScheduleError> {
    rule.validate()?;
    if rule.group_id != group.id || !rule.occurs_on(original_date) {
        return Ok(None);
    }
    if exception.is_some_and(|value| {
        value.recurrence_rule_id != rule.id || value.original_date != original_date
    }) {
        return Err(ScheduleError::InvalidExceptionReference {
            exception_id: exception.map_or(Uuid::nil(), |value| value.id),
        });
    }
    materialize_occurrence(policy, group, rule, original_date, exception).map(Some)
}

fn materialize_occurrence(
    policy: &SchedulePolicy,
    group: &GroupSchedulePolicy,
    rule: &RecurrenceRule,
    original_date: NaiveDate,
    exception: Option<&LessonException>,
) -> Result<ScheduleOccurrence, ScheduleError> {
    let changes = match exception.map(|value| &value.kind) {
        Some(LessonExceptionKind::Override { changes }) => Some(changes),
        _ => None,
    };
    let effective = match exception.map(|value| &value.kind) {
        Some(LessonExceptionKind::Cancelled { effective }) => effective.as_ref(),
        _ => None,
    };

    let original_start_time = exception
        .map(|value| value.original.start_time)
        .unwrap_or(rule.start_time);
    let original_end_time = exception
        .map(|value| value.original.end_time)
        .unwrap_or(rule.end_time);
    let date = effective
        .map(|value| value.date)
        .or_else(|| changes.and_then(|value| value.date))
        .unwrap_or(original_date);
    let start_time = effective
        .map(|value| value.start_time)
        .or_else(|| changes.and_then(|value| value.start_time))
        .unwrap_or(rule.start_time);
    let end_time = effective
        .map(|value| value.end_time)
        .or_else(|| changes.and_then(|value| value.end_time))
        .unwrap_or(rule.end_time);
    if start_time >= end_time {
        return Err(ScheduleError::InvalidEffectiveTime {
            rule_id: rule.id,
            original_date,
        });
    }

    let branch_id = effective
        .map(|value| value.branch_id)
        .or_else(|| changes.and_then(|value| value.branch_id))
        .or(rule.branch_id_override)
        .unwrap_or(group.branch_id);
    let room_id = effective.map_or_else(
        || {
            resolve_nullable(
                changes.map_or(&NullableOverride::Inherit, |value| &value.room_id),
                &rule.room_id_override,
                group.room_id,
            )
        },
        |value| value.room_id,
    );
    let teacher_ids = effective
        .map(|value| value.teacher_ids.clone())
        .or_else(|| changes.and_then(|value| value.teacher_ids.clone()))
        .or_else(|| rule.teacher_ids_override.clone())
        .unwrap_or_else(|| group.teacher_ids.clone());
    let capacity = effective.map_or_else(
        || {
            resolve_nullable(
                changes.map_or(&NullableOverride::Inherit, |value| &value.capacity),
                &rule.capacity_override,
                group.capacity,
            )
        },
        |value| value.capacity,
    );
    let trial_policy = effective
        .map(|value| value.trial_policy.clone())
        .or_else(|| changes.and_then(|value| value.trial_policy.clone()))
        .or_else(|| rule.trial_policy_override.clone())
        .or_else(|| group.trial_policy_override.clone())
        .unwrap_or_else(|| policy.default_trial_policy.clone());
    let single_visit_allowed = effective
        .map(|value| value.allow_single_visits)
        .or_else(|| changes.and_then(|value| value.allow_single_visits))
        .or(group.allow_single_visits_override)
        .unwrap_or(policy.allow_single_visits_by_default);
    let moved = date != original_date || start_time != rule.start_time || end_time != rule.end_time;
    let status = match exception.map(|value| &value.kind) {
        Some(LessonExceptionKind::Cancelled { .. }) => OccurrenceStatus::Cancelled,
        Some(_) if moved => OccurrenceStatus::Moved,
        Some(_) => OccurrenceStatus::Modified,
        None => OccurrenceStatus::Scheduled,
    };

    Ok(ScheduleOccurrence {
        lesson_ref: StableLessonReference {
            recurrence_rule_id: rule.id,
            original_date,
        },
        group_id: group.id,
        branch_id,
        room_id,
        teacher_ids,
        original_start_time,
        original_end_time,
        date,
        start_time,
        end_time,
        capacity,
        trial_policy,
        single_visit_allowed,
        track_attendance: group
            .track_attendance_override
            .unwrap_or(policy.track_attendance_by_default),
        status,
        exception_id: exception.map(|value| value.id),
    })
}

fn exception_target_date(exception: &LessonException) -> Option<NaiveDate> {
    match &exception.kind {
        LessonExceptionKind::Cancelled { effective } => effective.as_ref().map(|value| value.date),
        LessonExceptionKind::Override { changes } => changes.date,
    }
}

fn resolve_nullable<T: Clone>(
    occurrence: &NullableOverride<T>,
    rule: &NullableOverride<T>,
    group: Option<T>,
) -> Option<T> {
    match occurrence {
        NullableOverride::Set(value) => Some(value.clone()),
        NullableOverride::Clear => None,
        NullableOverride::Inherit => match rule {
            NullableOverride::Set(value) => Some(value.clone()),
            NullableOverride::Clear => None,
            NullableOverride::Inherit => group,
        },
    }
}

fn unique_count<T: Ord + Copy>(values: &[T]) -> usize {
    values.iter().copied().collect::<BTreeSet<_>>().len()
}

