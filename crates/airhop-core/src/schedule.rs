    #[test]
    fn moved_exception_enters_effective_range_by_stable_reference() {
        let moved = LessonException {
            id: uuid(20),
            recurrence_rule_id: uuid(10),
            original_date: date("2026-08-11"),
            original: original(),
            kind: LessonExceptionKind::Override {
                changes: OccurrenceOverride {
                    date: Some(date("2026-08-20")),
                    ..OccurrenceOverride::default()
                },
            },
        };
        let occurrences = materialize_schedule(
            &policy(),
            &[group()],
            &[rule()],
            &[moved],
            ScheduleRange {
                starts_on: date("2026-08-20"),
                ends_on: date("2026-08-20"),
            },
            MaterializeScheduleOptions::default(),
        )
        .expect("materialize");

        assert_eq!(occurrences.len(), 2);
        assert!(occurrences.iter().any(|value| {
            value.lesson_ref.original_date == date("2026-08-11") && value.date == date("2026-08-20")
        }));
    }

