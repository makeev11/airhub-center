/// A three-state override that distinguishes inheritance from explicit clearing.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub enum NullableOverride<T> {
    /// Keep the inherited value.
    #[default]
    Inherit,
    /// Explicitly remove the inherited value.
    Clear,
    /// Replace the inherited value.
    Set(T),
}

/// A recurring schedule definition.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RecurrenceRule {
    /// Stable rule identifier.
    pub id: Uuid,
    /// Group that owns the series.
    pub group_id: Uuid,
    /// First possible original date, inclusive.
    pub starts_on: NaiveDate,
    /// Last possible original date, inclusive.
    pub ends_on: NaiveDate,
    /// Weekdays generated by the rule.
    pub weekdays: BTreeSet<Weekday>,
    /// Local start time.
    pub start_time: NaiveTime,
    /// Local end time.
    pub end_time: NaiveTime,
    /// Optional branch override.
    pub branch_id_override: Option<Uuid>,
    /// Room override with explicit clear support.
    pub room_id_override: NullableOverride<Uuid>,
    /// Optional teacher replacement.
    pub teacher_ids_override: Option<Vec<Uuid>>,
    /// Capacity override with explicit clear support.
    pub capacity_override: NullableOverride<u32>,
    /// Optional trial-policy replacement.
    pub trial_policy_override: Option<TrialPolicy>,
    /// Whether the rule is active in the operational schedule.
    pub active: bool,
}

impl RecurrenceRule {
    /// Returns whether the rule owns an occurrence with this original date.
    pub fn occurs_on(&self, date: NaiveDate) -> bool {
        date >= self.starts_on
            && date <= self.ends_on
            && self.weekdays.contains(&Weekday::from(date.weekday()))
    }

    fn validate(&self) -> Result<(), ScheduleError> {
        if self.starts_on > self.ends_on {
            return Err(ScheduleError::ReversedRuleRange { rule_id: self.id });
        }
        if self.start_time >= self.end_time {
            return Err(ScheduleError::InvalidRuleTime { rule_id: self.id });
        }
        if self.weekdays.is_empty() {
            return Err(ScheduleError::EmptyRuleWeekdays { rule_id: self.id });
        }
        if self
            .teacher_ids_override
            .as_ref()
            .is_some_and(|teachers| unique_count(teachers) != teachers.len())
        {
            return Err(ScheduleError::DuplicateTeachers { rule_id: self.id });
        }
        Ok(())
    }
}

