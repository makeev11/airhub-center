/// The semantic kind and payload of a lesson exception.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LessonExceptionKind {
    /// The occurrence is cancelled. `effective` preserves a prior override.
    Cancelled {
        /// Fully resolved values before cancellation, when a prior override existed.
        effective: Option<OccurrenceEffective>,
    },
    /// The occurrence remains active with partial changes.
    Override {
        /// Changes relative to the recurrence and group defaults.
        changes: OccurrenceOverride,
    },
}

/// One exception addressed by stable recurrence rule and original date.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LessonException {
    /// Stable exception identifier.
    pub id: Uuid,
    /// Recurrence rule containing the original occurrence.
    pub recurrence_rule_id: Uuid,
    /// Original recurrence date.
    pub original_date: NaiveDate,
    /// Immutable original values retained for audit and display.
    pub original: LessonOriginal,
    /// Semantic exception data.
    pub kind: LessonExceptionKind,
}

/// Materialized lifecycle of a schedule occurrence.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum OccurrenceStatus {
    /// No exception changed the occurrence.
    Scheduled,
    /// The effective date or time changed.
    Moved,
    /// A non-time field changed.
    Modified,
    /// The occurrence is cancelled.
    Cancelled,
}

