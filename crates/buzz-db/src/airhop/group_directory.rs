async fn replace_rule_children(
    transaction: &mut sqlx::Transaction<'_, sqlx::Postgres>,
    tenant: &TenantContext,
    organization_id: Uuid,
    rule_id: Uuid,
    rule: &RecurrenceRuleInput,
) -> Result<()> {
    let weekdays: Vec<String> = rule
        .weekdays
        .iter()
        .map(|weekday| weekday_str(*weekday).to_owned())
        .collect();
    for weekday in &rule.weekdays {
        sqlx::query(
            "INSERT INTO airhop_recurrence_weekdays \
             (community_id, organization_id, recurrence_rule_id, weekday) \
             VALUES ($1, $2, $3, $4) ON CONFLICT DO NOTHING",
        )
        .bind(tenant.community().as_uuid())
        .bind(organization_id)
        .bind(rule_id)
        .bind(weekday_str(*weekday))
        .execute(&mut **transaction)
        .await?;
    }
    sqlx::query(
        "DELETE FROM airhop_recurrence_weekdays \
         WHERE community_id = $1 AND organization_id = $2 AND recurrence_rule_id = $3 \
           AND NOT (weekday = ANY($4::text[]))",
    )
    .bind(tenant.community().as_uuid())
    .bind(organization_id)
    .bind(rule_id)
    .bind(&weekdays)
    .execute(&mut **transaction)
    .await?;
    sqlx::query(
        "DELETE FROM airhop_recurrence_teachers \
         WHERE community_id = $1 AND organization_id = $2 AND recurrence_rule_id = $3",
    )
    .bind(tenant.community().as_uuid())
    .bind(organization_id)
    .bind(rule_id)
    .execute(&mut **transaction)
    .await?;
    if let Some(teacher_ids) = &rule.teacher_ids_override {
        for teacher_id in teacher_ids {
            sqlx::query(
                "INSERT INTO airhop_recurrence_teachers \
                 (community_id, organization_id, recurrence_rule_id, teacher_id) \
                 VALUES ($1, $2, $3, $4)",
            )
            .bind(tenant.community().as_uuid())
            .bind(organization_id)
            .bind(rule_id)
            .bind(teacher_id)
            .execute(&mut **transaction)
            .await?;
        }
    }
    Ok(())
}

