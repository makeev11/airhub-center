fn validate_create_input(input: &CreateGroupInput) -> Result<()> {
    if input.group.status != GroupStatus::Active
        || input.active_rules.iter().any(|rule| rule.id.is_some())
    {
        return Err(DbError::InvalidData(
            "new AirHub group or recurrence identity is invalid".to_owned(),
        ));
    }
    validate_common(&input.group, &input.active_rules, &input.actor)
}

fn validate_put_input(input: &PutGroupInput) -> Result<()> {
    if input.group_id.is_nil() || input.expected_version <= 0 {
        return Err(DbError::InvalidData(
            "AirHub group identity or version is invalid".to_owned(),
        ));
    }
    validate_common(&input.group, &input.active_rules, &input.actor)
}

fn validate_common(
    group: &GroupDefinition,
    rules: &[RecurrenceRuleInput],
    actor: &AirhopActor,
) -> Result<()> {
    actor.validate()?;
    let teacher_ids = group.teacher_ids.iter().copied().collect::<BTreeSet<_>>();
    let rule_ids = rules
        .iter()
        .filter_map(|rule| rule.id)
        .collect::<BTreeSet<_>>();
    if actor.kind != ActorKind::Staff
        || group.branch_id.is_nil()
        || group.room_id.is_some_and(|id| id.is_nil())
        || group.name.trim().is_empty()
        || group.name.chars().count() > 200
        || group
            .description
            .as_ref()
            .is_some_and(|value| value.chars().count() > 4_000)
        || group.min_age_months.is_some_and(|value| value < 0)
        || group.max_age_months.is_some_and(|value| value < 0)
        || matches!((group.min_age_months, group.max_age_months), (Some(min), Some(max)) if min > max)
        || group.capacity.is_some_and(|value| value <= 0)
        || group.teacher_ids.len() > MAX_TEACHERS
        || teacher_ids.len() != group.teacher_ids.len()
        || teacher_ids.contains(&Uuid::nil())
        || rules.is_empty()
        || rules.len() > MAX_RULES
        || rule_ids.len() != rules.iter().filter(|rule| rule.id.is_some()).count()
        || !valid_trial_policy(group.trial_policy_override.as_ref())
        || rules.iter().any(|rule| !valid_rule(rule))
    {
        return Err(DbError::InvalidData(
            "AirHub group input is invalid".to_owned(),
        ));
    }
    Ok(())
}

fn valid_rule(rule: &RecurrenceRuleInput) -> bool {
    let weekdays = rule.weekdays.iter().copied().collect::<BTreeSet<_>>();
    let teachers = rule
        .teacher_ids_override
        .as_ref()
        .map(|ids| ids.iter().copied().collect::<BTreeSet<_>>());
    !rule.id.is_some_and(|id| id.is_nil())
        && rule.starts_on <= rule.ends_on
        && rule.start_time < rule.end_time
        && !rule.weekdays.is_empty()
        && weekdays.len() == rule.weekdays.len()
        && !rule.branch_id_override.is_some_and(|id| id.is_nil())
        && !rule.room_id_override.is_some_and(|id| id.is_nil())
        && (rule.room_override_set || rule.room_id_override.is_none())
        && rule.capacity_override.is_none_or(|value| value > 0)
        && (rule.capacity_override_set || rule.capacity_override.is_none())
        && rule.teacher_ids_override.as_ref().is_none_or(|ids| {
            ids.len() <= MAX_TEACHERS
                && teachers
                    .as_ref()
                    .is_some_and(|unique| unique.len() == ids.len())
                && !ids.contains(&Uuid::nil())
        })
        && valid_trial_policy(rule.trial_policy_override.as_ref())
}

fn valid_trial_policy(policy: Option<&TrialPolicy>) -> bool {
    match policy {
        Some(TrialPolicy::Paid { price }) => {
            price.amount_minor <= 9_007_199_254_740_991
                && price.currency.len() == 3
                && price.currency.bytes().all(|byte| byte.is_ascii_uppercase())
        }
        _ => true,
    }
}

fn optional_json<T: Serialize>(value: Option<&T>) -> Result<Option<Value>> {
    value
        .map(serde_json::to_value)
        .transpose()
        .map_err(Into::into)
}

fn clean_optional(value: &Option<String>) -> Option<&str> {
    value
        .as_deref()
        .map(str::trim)
        .filter(|value| !value.is_empty())
}

const fn weekday_str(weekday: Weekday) -> &'static str {
    match weekday {
        Weekday::Monday => "monday",
        Weekday::Tuesday => "tuesday",
        Weekday::Wednesday => "wednesday",
        Weekday::Thursday => "thursday",
        Weekday::Friday => "friday",
        Weekday::Saturday => "saturday",
        Weekday::Sunday => "sunday",
    }
}

fn parse_weekday(value: &str) -> Result<Weekday> {
    match value {
        "monday" => Ok(Weekday::Monday),
        "tuesday" => Ok(Weekday::Tuesday),
        "wednesday" => Ok(Weekday::Wednesday),
        "thursday" => Ok(Weekday::Thursday),
        "friday" => Ok(Weekday::Friday),
        "saturday" => Ok(Weekday::Saturday),
        "sunday" => Ok(Weekday::Sunday),
        other => Err(DbError::InvalidData(format!(
            "unknown AirHub recurrence weekday {other:?}"
        ))),
    }
}

