async fn validate_group_links(
    transaction: &mut sqlx::Transaction<'_, sqlx::Postgres>,
    tenant: &TenantContext,
    organization_id: Uuid,
    group: &GroupDefinition,
    current_teacher_ids: &BTreeSet<Uuid>,
    current_room_id: Option<Uuid>,
) -> Result<()> {
    if let Some(room_id) = group.room_id {
        let row = sqlx::query(
            "SELECT branch_id, status FROM airhop_rooms \
             WHERE community_id = $1 AND organization_id = $2 AND id = $3 FOR SHARE",
        )
        .bind(tenant.community().as_uuid())
        .bind(organization_id)
        .bind(room_id)
        .fetch_optional(&mut **transaction)
        .await?
        .ok_or_else(|| DbError::NotFound("AirHub room".to_owned()))?;
        let branch_id: Uuid = row.try_get("branch_id")?;
        let status: String = row.try_get("status")?;
        if branch_id != group.branch_id || (status != "active" && current_room_id != Some(room_id))
        {
            return Err(DbError::NotFound(
                "active AirHub room in group branch".to_owned(),
            ));
        }
    }
    validate_teacher_ids(
        transaction,
        tenant,
        organization_id,
        &group.teacher_ids,
        current_teacher_ids,
    )
    .await
}

async fn validate_rule_links(
    transaction: &mut sqlx::Transaction<'_, sqlx::Postgres>,
    tenant: &TenantContext,
    organization_id: Uuid,
    group: &GroupDefinition,
    rule: &RecurrenceRuleInput,
) -> Result<()> {
    let effective_branch = rule.branch_id_override.unwrap_or(group.branch_id);
    if rule.branch_id_override.is_some() {
        require_active_branch(transaction, tenant, organization_id, effective_branch).await?;
    }
    if rule.room_override_set {
        if let Some(room_id) = rule.room_id_override {
            let found: bool = sqlx::query_scalar(
                "SELECT EXISTS(SELECT 1 FROM airhop_rooms \
                 WHERE community_id = $1 AND organization_id = $2 AND id = $3 \
                   AND branch_id = $4 AND status = 'active')",
            )
            .bind(tenant.community().as_uuid())
            .bind(organization_id)
            .bind(room_id)
            .bind(effective_branch)
            .fetch_one(&mut **transaction)
            .await?;
            if !found {
                return Err(DbError::NotFound(
                    "active AirHub recurrence room".to_owned(),
                ));
            }
        }
    } else if rule.room_id_override.is_some() {
        return Err(DbError::InvalidData(
            "AirHub recurrence room override is inconsistent".to_owned(),
        ));
    }
    if let Some(teacher_ids) = &rule.teacher_ids_override {
        validate_teacher_ids(
            transaction,
            tenant,
            organization_id,
            teacher_ids,
            &BTreeSet::new(),
        )
        .await?;
    }
    Ok(())
}

