/// Lifecycle of an operational group.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum GroupStatus {
    /// Available in the operational schedule.
    Active,
    /// Retained for history but unavailable for new operational assignments.
    Archived,
}

impl GroupStatus {
    const fn as_db_str(self) -> &'static str {
        match self {
            Self::Active => "active",
            Self::Archived => "archived",
        }
    }

    fn from_db(value: &str) -> Result<Self> {
        match value {
            "active" => Ok(Self::Active),
            "archived" => Ok(Self::Archived),
            other => Err(DbError::InvalidData(format!(
                "unknown AirHub group status {other:?}"
            ))),
        }
    }
}

/// Lifecycle of a recurrence rule.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RecurrenceRuleStatus {
    /// Included in future schedule materialization.
    Active,
    /// Retained for stable historical lesson references.
    Archived,
}

impl RecurrenceRuleStatus {
    fn from_db(value: &str) -> Result<Self> {
        match value {
            "active" => Ok(Self::Active),
            "archived" => Ok(Self::Archived),
            other => Err(DbError::InvalidData(format!(
                "unknown AirHub recurrence-rule status {other:?}"
            ))),
        }
    }
}

/// Mutable fields of one group, shared by create and replacement commands.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GroupDefinition {
    /// Parent branch.
    pub branch_id: Uuid,
    /// Optional default room inside the parent branch.
    pub room_id: Option<Uuid>,
    /// Human-readable group name.
    pub name: String,
    /// Optional staff-facing description.
    pub description: Option<String>,
    /// Default teachers.
    pub teacher_ids: Vec<Uuid>,
    /// Inclusive minimum age in months.
    pub min_age_months: Option<i32>,
    /// Inclusive maximum age in months.
    pub max_age_months: Option<i32>,
    /// Default capacity, or unbounded when absent.
    pub capacity: Option<i32>,
    /// Group-specific trial policy.
    pub trial_policy_override: Option<TrialPolicy>,
    /// Group-specific attendance setting.
    pub track_attendance_override: Option<bool>,
    /// Group-specific one-off visit setting.
    pub allow_single_visits_override: Option<bool>,
    /// Desired group lifecycle.
    pub status: GroupStatus,
}

/// One active recurrence rule supplied as part of an atomic group command.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RecurrenceRuleInput {
    /// Existing server-owned rule id, or absent for a newly allocated rule.
    pub id: Option<Uuid>,
    /// Inclusive first original date.
    pub starts_on: NaiveDate,
    /// Inclusive last original date.
    pub ends_on: NaiveDate,
    /// Weekdays generated by this rule.
    pub weekdays: Vec<Weekday>,
    /// Local lesson start.
    pub start_time: NaiveTime,
    /// Local lesson end.
    pub end_time: NaiveTime,
    /// Optional branch replacement.
    pub branch_id_override: Option<Uuid>,
    /// Whether the room override is explicit rather than inherited.
    pub room_override_set: bool,
    /// Explicit room replacement, or `None` to clear when the override is set.
    pub room_id_override: Option<Uuid>,
    /// Optional teacher-list replacement.
    pub teacher_ids_override: Option<Vec<Uuid>>,
    /// Whether the capacity override is explicit rather than inherited.
    pub capacity_override_set: bool,
    /// Explicit capacity replacement, or `None` to clear when the override is set.
    pub capacity_override: Option<i32>,
    /// Rule-specific trial policy.
    pub trial_policy_override: Option<TrialPolicy>,
}

